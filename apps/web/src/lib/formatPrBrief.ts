import type { PRTrustBrief } from "@cartana/shared";

/**
 * Formats a PRTrustBrief into GitHub-native Markdown, ready to paste into a
 * pull request review comment. Written as a document: sentence case, an
 * accounting table up top, evidence shown as diff blocks, no emoji, no
 * exclamation marks, no em dashes.
 */
export function formatPRBriefAsGithubMarkdown(brief: PRTrustBrief): string {
  const unverified = brief.verdicts.filter((v) => v.evidenceVerified === false).length;
  const verified = brief.verdicts.filter((v) => v.evidenceVerified === true).length;

  const riskSection =
    brief.riskAlerts.length > 0
      ? [
          "### Risk alerts",
          "",
          ...brief.riskAlerts.map((a) => {
            const files =
              a.affectedFiles && a.affectedFiles.length > 0
                ? ` (files: ${a.affectedFiles.map((f) => `\`${f}\``).join(", ")})`
                : "";
            return `- **${a.severity}** ${a.title}: ${a.description}${files}`;
          }),
          "",
        ].join("\n")
      : "";

  const verdictsSection = brief.verdicts
    .map((v) => {
      const evidenceState =
        v.evidenceVerified === true
          ? "found in the diff"
          : v.evidenceVerified === false
            ? "not found in the diff"
            : "no evidence claimed";

      const snippetBlock = v.evidenceSnippet
        ? `\n\`\`\`diff\n${v.evidenceSnippet}\n\`\`\`\n`
        : "";

      return `<details>
<summary><b>${v.reqId}: ${v.title}</b> : ${v.status}</summary>

**Verdict:** ${v.status} (confidence: ${v.confidence})
${v.evidenceFile ? `**Evidence:** \`${v.evidenceFile}\` (${evidenceState})` : "**Evidence:** none claimed"}
${snippetBlock}
**Why:** ${v.rationale}

</details>`;
    })
    .join("\n\n");

  return `## Cartana trust report

| Metric | Value |
|---|---|
| Trust | ${brief.trustLevel} |
| Coverage | ${brief.coverageScore}% |
| Requirements | ${brief.totalRequirements} total, ${brief.coveredCount} covered, ${brief.partialCount} partial, ${brief.missingCount} missing |
| Evidence checked | ${verified} claim${verified === 1 ? "" : "s"} found in the diff |
| Evidence not found | ${unverified} claim${unverified === 1 ? "" : "s"} |

### Summary

${brief.summary}

${riskSection}### Requirements

${verdictsSection}

---
*Generated by Cartana*`;
}

/** Helper to trigger browser file download. */
export function downloadFile(filename: string, content: string, contentType: string) {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
